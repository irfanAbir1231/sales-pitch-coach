import 'dart:math';

import '../models/product.dart';
import '../services/settings_store.dart';
import 'providers.dart';
import 'score_result.dart';

class NoProviderConfigured implements Exception {
  @override
  String toString() => 'No AI provider key is set. Add one in Admin. / কোনো AI provider এর API key সেট করা নেই। Admin থেকে key দিন।';
}

/// Picks the active provider (with optional fallback to the others).
class AiService {
  final SettingsStore settings;
  AiService(this.settings);

  final _rng = Random();

  /// Runs [action] against the active provider, then the others if fallback is on.
  Future<T> _withProviders<T>(Future<T> Function(LlmProvider, ProviderConfig) action) async {
    final active = allProviders.firstWhere((x) => x.id == settings.activeProviderId, orElse: () => allProviders.first);
    final order = [active, if (settings.fallbackEnabled) ...allProviders.where((x) => x != active)];

    Object? lastError;
    var tried = false;
    for (final provider in order) {
      final key = await settings.apiKey(provider);
      if (key == null || key.isEmpty) continue;
      tried = true;
      try {
        return await action(provider, ProviderConfig(key, settings.modelFor(provider)));
      } catch (e) {
        lastError = e;
      }
    }
    if (!tried) throw NoProviderConfigured();
    throw lastError!;
  }

  /// [question] is set in objection mode: [pitch] is then the answer to it.
  Future<ScoreResult> score(Product p, String pitch, {Objection? question, String language = 'bn'}) =>
      _withProviders((prov, cfg) => prov.score(cfg, p, pitch, question: question, language: language));

  /// Returns a retailer objection: a curated one when the dataset has it
  /// (and it differs from [previous]), otherwise one generated by the AI.
  Future<Objection> nextObjection(Product p, {String? previous}) async {
    final curated = p.objections.where((o) => o.question != previous).toList();
    if (curated.isNotEmpty) return curated[_rng.nextInt(curated.length)];
    return _withProviders((prov, cfg) => prov.generateObjection(cfg, p));
  }

  /// Used by the admin "Test connection" button.
  Future<String> test(LlmProvider provider, String key, String model) async {
    return provider.complete(ProviderConfig(key, model), 'Reply with the single word: OK', 'ping');
  }
}
